-- Jersey Orbit: initial schema.
-- Money is stored in whole paise (₹1 = 100) so that no amount is ever rounded.

CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

/* ---------- catalog ---------- */

CREATE TABLE collections (
  key   text PRIMARY KEY CHECK (key ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title text NOT NULL
);

-- Imported products keep their original ids, so carts already saved in customers' browsers stay valid.
-- New rows start far above those ids and stay below 2^53, which JavaScript can hold exactly.
CREATE TABLE products (
  id           bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 90000000000000) PRIMARY KEY,
  handle       text NOT NULL UNIQUE CHECK (handle ~ '^[a-z0-9]+([_-]+[a-z0-9]+)*$'),
  title        text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
  details      text[] NOT NULL DEFAULT '{}',
  is_published boolean NOT NULL DEFAULT false,
  sort_order   integer NOT NULL DEFAULT 0,          -- "Featured" order, lowest first
  version      integer NOT NULL DEFAULT 1,          -- stops one edit silently overwriting another
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX products_sort_idx ON products (sort_order, id);
CREATE TRIGGER products_updated_at BEFORE UPDATE ON products FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE product_variants (
  id               bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 90000000000000) PRIMARY KEY,
  product_id       bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  size             text NOT NULL CHECK (char_length(size) BETWEEN 1 AND 20),
  price_paise      integer NOT NULL CHECK (price_paise > 0),
  compare_at_paise integer CHECK (compare_at_paise > 0),   -- the struck-through "was" price
  is_available     boolean NOT NULL DEFAULT true,          -- the owner's on/off switch
  stock_qty        integer CHECK (stock_qty >= 0),         -- NULL means stock is not counted
  position         integer NOT NULL DEFAULT 0,
  -- deferred, so two sizes can swap names within one transaction
  CONSTRAINT product_variants_size_key UNIQUE (product_id, size) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE product_images (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  position   integer NOT NULL DEFAULT 0,
  width      integer NOT NULL CHECK (width > 0),
  height     integer NOT NULL CHECK (height > 0),
  url_small  text NOT NULL,   -- 480px wide
  url_large  text NOT NULL    -- 1200px wide
);
CREATE INDEX product_images_product_idx ON product_images (product_id, position, id);

CREATE TABLE product_collections (
  product_id     bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  collection_key text NOT NULL REFERENCES collections (key) ON DELETE CASCADE,
  PRIMARY KEY (product_id, collection_key)
);
CREATE INDEX product_collections_key_idx ON product_collections (collection_key);

/* ---------- admins ---------- */

CREATE TABLE admins (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  username      text NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9._-]{3,40}$'),
  password_hash text NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE admin_sessions (
  token_hash text PRIMARY KEY,   -- SHA-256 of the cookie value; the value itself is never stored
  admin_id   bigint NOT NULL REFERENCES admins (id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

/* ---------- orders ---------- */

CREATE SEQUENCE order_number_seq START WITH 1001;

CREATE TABLE orders (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_number   text NOT NULL UNIQUE DEFAULT ('JO-' || nextval('order_number_seq')),
  client_ref     uuid NOT NULL UNIQUE,   -- sent by the browser, so a repeated submit makes one order
  status         text NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'confirmed', 'packed', 'shipped', 'delivered', 'cancelled')),
  payment_status text NOT NULL DEFAULT 'unpaid' CHECK (payment_status IN ('unpaid', 'paid', 'refunded')),

  customer_name  text NOT NULL CHECK (char_length(customer_name) BETWEEN 1 AND 100),
  phone          text NOT NULL CHECK (phone ~ '^[6-9][0-9]{9}$'),
  address        text NOT NULL CHECK (char_length(address) BETWEEN 1 AND 500),
  city           text NOT NULL CHECK (char_length(city) BETWEEN 1 AND 100),
  pincode        text NOT NULL CHECK (pincode ~ '^[1-9][0-9]{5}$'),
  delivery_area  text NOT NULL CHECK (delivery_area IN ('kerala', 'india')),
  customer_note  text NOT NULL DEFAULT '' CHECK (char_length(customer_note) <= 500),

  subtotal_paise integer NOT NULL CHECK (subtotal_paise > 0),
  shipping_paise integer NOT NULL CHECK (shipping_paise >= 0),
  total_paise    integer NOT NULL,

  courier        text NOT NULL DEFAULT '' CHECK (char_length(courier) <= 80),
  tracking_id    text NOT NULL DEFAULT '' CHECK (char_length(tracking_id) <= 80),
  admin_note     text NOT NULL DEFAULT '' CHECK (char_length(admin_note) <= 1000),

  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT orders_total_adds_up CHECK (total_paise = subtotal_paise + shipping_paise)
);
CREATE INDEX orders_status_idx ON orders (status, created_at DESC);
CREATE INDEX orders_created_idx ON orders (created_at DESC);
CREATE INDEX orders_phone_idx ON orders (phone);
CREATE TRIGGER orders_updated_at BEFORE UPDATE ON orders FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Title, size and price are copied here, so editing a product later never changes a past order.
CREATE TABLE order_items (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id         bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  variant_id       bigint REFERENCES product_variants (id) ON DELETE SET NULL,
  product_title    text NOT NULL,
  size             text NOT NULL,
  unit_price_paise integer NOT NULL CHECK (unit_price_paise > 0),
  quantity         integer NOT NULL CHECK (quantity BETWEEN 1 AND 10),
  stock_taken      boolean NOT NULL DEFAULT false   -- true while this line holds counted stock
);
CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE INDEX order_items_variant_idx ON order_items (variant_id);

CREATE TABLE order_events (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id   bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  status     text NOT NULL,
  admin_id   bigint REFERENCES admins (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX order_events_order_idx ON order_events (order_id, id);
