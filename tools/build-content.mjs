#!/usr/bin/env node
/**
 * Builds assets/js/content.js (window.JO_CONTENT) from the policy pages saved in tools/cache/page_*.html.
 * The HTML is reduced to a small safe tag set so it can be dropped into the Policies page as-is.
 *
 *   node tools/build-content.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = path.join(ROOT, 'tools', 'cache');
const OUT = path.join(ROOT, 'assets', 'js', 'content.js');

const ALLOWED = new Set(['p', 'h1', 'h2', 'h3', 'h4', 'h5', 'ul', 'ol', 'li', 'strong', 'b', 'em', 'i', 'br', 'a', 'table', 'thead', 'tbody', 'tr', 'th', 'td']);

function sanitize(html) {
  return html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<(script|style|svg|form|button|noscript)[\s\S]*?<\/\1>/gi, '')
    .replace(/<\/?([a-z0-9]+)([^>]*)>/gi, (m, tag, attrs) => {
      const t = tag.toLowerCase();
      const closing = m.startsWith('</');
      if (!ALLOWED.has(t)) return '';
      if (closing) return `</${t}>`;
      if (t === 'a') {
        const href = /href\s*=\s*"([^"]*)"/i.exec(attrs)?.[1] || '';
        if (/^\s*javascript:/i.test(href)) return '<a>';
        const abs = href.startsWith('/') ? 'https://jerseyorbit.com' + href : href;
        return `<a href="${abs}" target="_blank" rel="noopener">`;
      }
      return `<${t}>`;
    })
    .replace(/&nbsp;/g, ' ')
    .replace(/<p>\s*(<br>)?\s*<\/p>/g, '')
    .replace(/\s*\n\s*/g, '\n')
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}

const out = {};
for (const k of ['shipping', 'refund', 'privacy', 'terms']) {
  let html = sanitize(fs.readFileSync(path.join(CACHE, `page_${k}.html`), 'utf8'));
  // the page template renders its own title, drop a leading duplicate heading from the policy body
  html = html.replace(/^\s*<h[1-3]>[\s\S]*?<\/h[1-3]>\s*/i, '');
  // "1. General Policy We do not…" runs on in the store's markup: put each numbered lead-in on its own line
  html = html.replace(/<b>(\d+\.\s[^<]{3,90})<\/b>\s*/g, '<b>$1</b><br>');
  out[k] = html;
}

fs.writeFileSync(OUT, '/* AUTO-GENERATED by tools/build-content.mjs — policy text mirrored from the live store */\nwindow.JO_CONTENT=' + JSON.stringify(out) + ';\n');
console.log(`Wrote ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
